const faultSelect = document.getElementById("fault-select");
const faultTask = document.getElementById("fault-task");

if(faultSelect && faultTask){
  faultSelect.innerHTML = Object.entries(faultInfo).map(([k, v]) => `<option value="${k}">${v.title}</option>`).join("");

  function renderFault(key){
    const item = faultInfo[key];
    faultTask.innerHTML = `
      <strong>${item.title}</strong>
      <p>${item.facts}</p>
      <p><b>Контрольный вопрос:</b> ${item.question}</p>
      <div class="fault-check-grid">
        ${item.probes.map((p, idx) => `<button class="probe-btn" data-probe="${idx}">🔍 ${p.label}</button>`).join("")}
      </div>
      <div id="probe-output" class="probe-result" style="display:none"></div>
      <details style="margin-top:14px">
        <summary style="cursor:pointer;color:var(--green);font-weight:700">Показать полный эталонный ответ по схеме</summary>
        <p style="margin-top:8px">${item.answer}</p>
      </details>
    `;

    faultTask.querySelectorAll(".probe-btn").forEach(btn => {
      btn.addEventListener("click", () => {
        const out = document.getElementById("probe-output");
        const probe = item.probes[Number(btn.dataset.probe)];
        out.style.display = "block";
        out.innerHTML = `<b>Результат проверки («Контролька»):</b> ${probe.res}`;
      });
    });
  }

  faultSelect.addEventListener("change", () => renderFault(faultSelect.value));
  renderFault(faultSelect.value);
}

