function renderRelays(filter=""){
  const box = document.getElementById("relay-list");
  if(!box) return;
  const q = filter.trim().toLowerCase();
  const list = relaysData.filter(r => r.code.toLowerCase().includes(q) || r.desc.toLowerCase().includes(q));
  box.innerHTML = list.map(r => `<div class="relay-item"><strong>${r.code}</strong><span>— ${r.desc}</span></div>`).join("");
}
renderRelays();
document.getElementById("relay-search")?.addEventListener("input", e => renderRelays(e.target.value));

